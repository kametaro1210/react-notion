import { atom } from 'jotai';
import { User } from '../users/user.entity';

/*
  【概要】
  ログイン中のユーザーをアプリ内で共有するための状態を用意する。
  Jotaiは、離れた画面や部品どうしで同じ情報を共有したいときに使う。
  例えると、currentUserAtomは「みんなで確認できる共有メモ」のようなもの。
  ユーザー情報のほか、画面のテーマや買い物かごの内容などの共有にも使える。

  【コードの意味】
  atom<User>()は、User型のユーザー情報を入れる状態を作る。
  初期値は未設定なので、まだログインしていない状態では値がない。

  【処理フロー】
  1. サインインに成功すると、Signin画面が取得したユーザーをこの状態に保存する。
  2. Layoutはこの状態を確認し、ユーザーがいなければ(ログインしていない状態)
      Signin画面へ移動させる。
  3. ユーザーがいればログイン中と判断し、Homeなどの画面を表示する。
*/

export const currentUserAtom = atom<User>();